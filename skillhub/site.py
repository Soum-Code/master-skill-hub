def build_site(slim: dict, candidates: list[dict]) -> None:
    skills = list(slim["skills"])
    for c in candidates:
        skills.append({"id": c["id"], "name": c["id"], "desc": c.get("desc", ""), "pack": c.get("pack", "general"),
                       "packs": [], "tags": [], "status": "candidate", "source": {"install": ""}})
    data = {"generated": slim["generated"], "packs": slim["packs"], "skills": skills}
    blob = json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    html = TEMPLATE.replace("__DATA__", blob).replace("__REPO__", REPO_SLUG)
    write_text(ROOT / "site" / "index.html", html)
